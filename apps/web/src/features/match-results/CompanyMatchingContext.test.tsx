import assert from "node:assert/strict";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import type { MatchingProfileView, MatchingProfileViewRow, MatchCard } from "@cunote/contracts";
(globalThis as typeof globalThis & { React: typeof React }).React = React;
const { CompanyMatchingContext, companyFactState } = await import("./CompanyMatchingContext");
const { MatchEvidenceComparison } = await import("./MatchEvidenceComparison");
const row = { dimension: "region", status: "known", displayValue: "서울", sourceKind: "authoritative_api", sourceLabel: "사업자 원천", asOf: "2026-10-01", completeness: "complete", editMode: "read_only", action: { kind: "none", label: "" } } as MatchingProfileViewRow;
const profile = { asOf: "2026-10-01", knownCount: 1, partialCount: 1, unknownCount: 1, rows: [row, { ...row, dimension: "biz_age", status: "partial", displayValue: "3년", completeness: "partial" }, { ...row, dimension: "target_type", sourceDisputed: true, displayValue: "법인" }, { ...row, dimension: "industry", status: "unknown", displayValue: "외부 값" }] } as MatchingProfileView;
assert.equal(companyFactState(row), "확인된 값");
assert.equal(companyFactState({ ...row, sourceDisputed: true }), "출처 충돌 · 확인 필요");
const a = renderToStaticMarkup(<CompanyMatchingContext profileView={profile} companyName="회사 A" />);
assert.ok(a.includes("회사 A") && a.includes("서울") && a.includes("사업자 원천"));
assert.ok(a.includes("일부 확인") && a.includes("출처 충돌 · 확인 필요") && a.includes("미확인"));
assert.equal(a.includes("외부 값"), false, "unknown 값은 확인된 사업자 정보처럼 노출하지 않는다");
assert.ok(a.indexOf("서울") < a.indexOf("<details"), "지역은 바로 표시한다");
assert.ok(a.indexOf("<details") < a.indexOf("3년"), "업력 등 보조 정보는 접힌 영역에 있다");
assert.ok(a.includes("업력·규모 등 나머지 사업자 정보 4개"));
const compact = renderToStaticMarkup(<CompanyMatchingContext profileView={profile} companyName="회사 A" compact />);
assert.ok(compact.includes("대조에 사용한 사업자 정보·출처 보기"));
assert.equal(/<details[^>]*\sopen(?:[=>\s])/.test(compact), false, "상세 문맥의 사실은 기본 접힘이다");
assert.ok(compact.indexOf("<details") < compact.indexOf("서울"), "실제 사실은 펼침 영역 안에 있다");
assert.equal(compact.split("직접 입력한 개인 매칭 답변과 원천 조회 정보를 함께 사용해요.").length - 1, 1, "접힌 설명 footer를 중복 출력하지 않는다");
const b = renderToStaticMarkup(<CompanyMatchingContext profileView={{ ...profile, rows: [{ ...row, displayValue: "부산" }] }} companyName="회사 B" temporary />);
assert.ok(b.includes("회사 B") && b.includes("부산") && b.includes("임시 정보"));
assert.equal(b.includes("서울"), false, "B 회사는 A 값을 재사용하지 않는다");
const match = { criteriaExtracted: true, matchingEvidence: { level: "verified" }, ruleTrace: [{ dimension: "region", result: "fail", label: "부산 소재 기업", companyValue: "서울" }, { dimension: "industry", result: "unknown", label: "제조업", unresolvedReason: "company_profile_missing" }] } as unknown as MatchCard;
const comparison = renderToStaticMarkup(<MatchEvidenceComparison match={match} />);
assert.ok(comparison.includes("부산 소재 기업") && comparison.includes("서울") && comparison.includes("불일치"));
assert.ok(comparison.includes("값 미확인") && comparison.includes("회사 정보가 없어"));
assert.equal(comparison.includes("확인된 기업정보와 일치"), false, "미확인 회사값을 일치로 추정하지 않는다");
const discovery = renderToStaticMarkup(<MatchEvidenceComparison match={{ ...match, matchingEvidence: { level: "discovery" } } as MatchCard} />);
assert.ok(discovery.includes("아직 대조하지 못했어요"));
assert.equal(discovery.includes("충족"), false);
console.log("company matching context: actual company values, provenance, partial/dispute/unknown and A/B isolation passed");
